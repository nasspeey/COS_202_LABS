public class Task5_1_Counting {
    public static void main(String[] args) {
        System.out.println("1 to 20:");
        for (int i = 1; i <= 20; i++) System.out.print(i + " ");
        System.out.println("\n\nEven numbers 20 down to 2:");
        for (int i = 20; i >= 2; i -= 2) System.out.print(i + " ");
        System.out.println();
    }
}
